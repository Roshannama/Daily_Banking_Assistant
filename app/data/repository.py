from typing import Protocol

class RepositoryError(Exception):
    pass

class BankingRepository(Protocol):
    """Identity is supplied by gateway only. Rows are scoped by customer at query time."""
    def records(self, customer: str, kind: str) -> list[dict]: ...
    def pin_hash(self, customer: str) -> str | None: ...
    def block_card(self, customer: str, resource: str, key: str) -> dict: ...
    def create_dispute(self, customer: str, resource: str, key: str) -> dict: ...
    def audit(self, event: dict) -> None: ...
